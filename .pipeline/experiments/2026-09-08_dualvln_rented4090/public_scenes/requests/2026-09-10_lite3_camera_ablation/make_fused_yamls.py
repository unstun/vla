"""Generate the fused-camera condition YAMLs (rounds 5-6) from the baseline YAML.

Text substitution like make_condition_yamls.py: every byte outside the replaced
blocks stays identical to public_scenes/configs/vln_public_scenes.yaml. Added:
three sim-sensor defaults entries and one lab-sensor entry (all registered by
fused_camera_plugin.py), their parameter blocks, and the fused_rgb_sensor task
block. Run from the experiment root:
  python3 public_scenes/requests/2026-09-10_lite3_camera_ablation/make_fused_yamls.py [condition...]
"""
import difflib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
REQ = Path(__file__).resolve().parent
COND = json.loads((REQ / 'conditions.json').read_text())
BASE = ROOT / COND['baseline']['habitat_yaml']

AGENT_LINE = "  - /habitat/simulator/agents@habitat.simulator.agents.main_agent: rgbd_agent\n"
LAB_LINES = "  - /habitat/task/lab_sensors:\n    - gps_sensor\n    - compass_sensor\n"
BASE_SENSORS = """          rgb_sensor:
            width: 640
            height: 480
            hfov: 79
          depth_sensor:
            width: 640
            height: 480
            hfov: 79
            min_depth: 0.0
            max_depth: 10.0
"""
BASE_TILT = "    tilt_angle: 15\n"
TASK_LINE = "  task:\n    measurements:\n"


def fmt(v):
    return '[' + ', '.join(repr(float(x)) for x in v) + ']'


def sensor_lines(key, s, depth=False):
    out = (f"          {key}:\n"
           f"            width: {int(s['width'])}\n"
           f"            height: {int(s['height'])}\n"
           f"            hfov: {int(s['hfov']) if float(s['hfov']).is_integer() else float(s['hfov'])}\n"
           f"            position: {fmt(s['position'])}\n"
           f"            orientation: {fmt(s['orientation'])}\n")
    if depth:
        out += (f"            min_depth: {float(s['min_depth'])}\n"
                f"            max_depth: {float(s['max_depth'])}\n")
        if 'normalize_depth' in s:
            out += f"            normalize_depth: {str(bool(s['normalize_depth']))}\n"
    return out


def main():
    base = BASE.read_text()
    for needle in (AGENT_LINE, LAB_LINES, BASE_SENSORS, BASE_TILT, TASK_LINE):
        if base.count(needle) != 1:
            sys.exit(f'baseline YAML does not contain exactly once: {needle!r}')
    diffs = {}
    # Optional condition filter. Regenerating a condition whose runs are already recorded would change the
    # YAML's SHA-256 and orphan the hashes in those runs' inputs.json, so round 6 passes c9_fused_down9 only.
    only = set(sys.argv[1:])
    for name, c in COND['conditions'].items():
        if 'fused' not in c:
            continue
        if only and name not in only:
            continue
        f = c['fused']
        text = base
        text = text.replace(AGENT_LINE, AGENT_LINE +
            "  - /habitat/simulator/sim_sensors@habitat.simulator.agents.main_agent.sim_sensors.fused_head_rgb_sensor: fused_head_rgb_sensor\n"
            "  - /habitat/simulator/sim_sensors@habitat.simulator.agents.main_agent.sim_sensors.fused_d435_rgb_sensor: fused_d435_rgb_sensor\n"
            "  - /habitat/simulator/sim_sensors@habitat.simulator.agents.main_agent.sim_sensors.fused_d435_depth_sensor: fused_d435_depth_sensor\n")
        text = text.replace(LAB_LINES, LAB_LINES + "    - fused_rgb_sensor\n")
        sensors = (sensor_lines('rgb_sensor', f['virtual']) +
                   sensor_lines('depth_sensor', f['depth_for_evaluator'], depth=True) +
                   sensor_lines('fused_head_rgb_sensor', f['head_rgb']) +
                   sensor_lines('fused_d435_rgb_sensor', f['d435_rgb']) +
                   sensor_lines('fused_d435_depth_sensor', f['d435_depth'], depth=True))
        text = text.replace(BASE_SENSORS, sensors)
        text = text.replace(BASE_TILT, f"    tilt_angle: {int(c['habitat']['tilt_angle'])}\n")
        task_block = ("  task:\n"
                      "    lab_sensors:\n"
                      "      fused_rgb_sensor:\n"
                      f"        uuid: {f['virtual']['uuid']}\n"
                      "        virtual_sensor_key: rgb_sensor\n"
                      "        head_sensor_key: fused_head_rgb_sensor\n"
                      "        d435_rgb_sensor_key: fused_d435_rgb_sensor\n"
                      "        d435_depth_sensor_key: fused_d435_depth_sensor\n"
                      f"        feather_rows: {int(f['fusion']['feather_rows'])}\n"
                      f"        depth_valid_max_m: {float(f['fusion']['depth_valid_max_m'])}\n"
                      "    measurements:\n")
        text = text.replace(TASK_LINE, task_block)
        pd = float(c['pitch_down_deg'])
        pitch_desc = 'level' if pd == 0 else f'{pd:g} deg down'  # 'level' keeps c7/c8 byte-identical
        header = (f"# Camera condition {name}: {c['label']}. Generated by {REQ.name}/make_fused_yamls.py from "
                  f"{BASE.name}; adds three rendered mounts and the fused_rgb_sensor task sensor (both registered by "
                  f"{REQ.name}/fused_camera_plugin.py, imported by {Path(c['eval_config']).name}); rgb_sensor/depth_sensor "
                  f"are the {pitch_desc} virtual camera; tilt_angle {int(c['habitat']['tilt_angle'])}.\n")
        text = text.replace('# @package _global_\n', '# @package _global_\n' + header, 1)
        out = ROOT / c['habitat_yaml']
        out.write_text(text)
        d = ''.join(difflib.unified_diff(base.splitlines(True), text.splitlines(True),
                                         fromfile=str(BASE.relative_to(ROOT)), tofile=str(out.relative_to(ROOT))))
        diffs[name] = d
        print(f'wrote {out.relative_to(ROOT)}')
    (REQ / 'yaml_diffs_fused.json').write_text(json.dumps(diffs, indent=2) + '\n')
    print('YAML_DIFFS_WRITTEN', (REQ / 'yaml_diffs_fused.json').relative_to(ROOT))


if __name__ == '__main__':
    main()
