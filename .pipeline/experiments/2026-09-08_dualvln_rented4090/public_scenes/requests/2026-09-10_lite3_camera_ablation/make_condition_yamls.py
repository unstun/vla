"""Generate one Habitat YAML per camera condition from the baseline YAML.

Text substitution, not a YAML round-trip, so every byte outside the two sensor
blocks and the tilt_angle line stays identical to public_scenes/configs/
vln_public_scenes.yaml. Prints a unified diff per condition and refuses to run
if the baseline no longer contains the exact blocks it expects.

Run from the experiment root:
  python3 public_scenes/requests/2026-09-10_lite3_camera_ablation/make_condition_yamls.py
"""
import difflib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
REQ = Path(__file__).resolve().parent
COND = json.loads((REQ / 'conditions.json').read_text())
BASE = ROOT / COND['baseline']['habitat_yaml']

BASE_SENSORS = """          rgb_sensor:
            width: 640
            height: 480
            hfov: 79
          depth_sensor:
            width: 640
            height: 480
            hfov: 79
            min_depth: 0.0
            max_depth: 10.0
"""
BASE_TILT = "    tilt_angle: 15\n"


def fmt(v):
    return '[' + ', '.join(repr(float(x)) for x in v) + ']'


def sensors_block(h):
    return (
        "          rgb_sensor:\n"
        "            width: 640\n"
        "            height: 480\n"
        f"            hfov: {int(h['hfov'])}\n"
        f"            position: {fmt(h['position'])}\n"
        f"            orientation: {fmt(h['orientation'])}\n"
        "          depth_sensor:\n"
        "            width: 640\n"
        "            height: 480\n"
        f"            hfov: {int(h['hfov'])}\n"
        f"            position: {fmt(h['position'])}\n"
        f"            orientation: {fmt(h['orientation'])}\n"
        "            min_depth: 0.0\n"
        "            max_depth: 10.0\n"
    )


def main():
    base = BASE.read_text()
    if base.count(BASE_SENSORS) != 1 or base.count(BASE_TILT) != 1:
        sys.exit('baseline YAML does not contain the expected sensor block and tilt line exactly once')
    if not base.startswith('# @package _global_\n'):
        sys.exit('baseline YAML must start with the Hydra package line')
    diffs = {}
    for name, c in COND['conditions'].items():
        h = c['habitat']
        text = base.replace(BASE_SENSORS, sensors_block(h))
        text = text.replace(BASE_TILT, f"    tilt_angle: {int(h['tilt_angle'])}\n")
        header = (f"# Camera condition {name}: {c['label']}. Generated by "
                  f"{REQ.name}/make_condition_yamls.py from {BASE.name}; only the sensor "
                  "position/orientation/hfov and tilt_angle differ.\n")
        text = text.replace('# @package _global_\n', '# @package _global_\n' + header, 1)
        out = ROOT / c['habitat_yaml']
        out.write_text(text)
        d = ''.join(difflib.unified_diff(base.splitlines(True), text.splitlines(True),
                                         fromfile=str(BASE.relative_to(ROOT)),
                                         tofile=str(out.relative_to(ROOT))))
        diffs[name] = d
        print(f'wrote {out.relative_to(ROOT)}')
        print(d)
    (REQ / 'yaml_diffs.json').write_text(json.dumps(diffs, indent=2) + '\n')
    print('YAML_DIFFS_WRITTEN', (REQ / 'yaml_diffs.json').relative_to(ROOT))


if __name__ == '__main__':
    main()
